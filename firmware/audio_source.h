// Кто отдаёт выводу готовые сэмплы. Вывод (audio_output_1bit.h в Wokwi,
// I2S-кодек на железе — стори 4.7) не знает ни про движок, ни про паттерн:
// он просто просит n сэмплов и ставит их в очередь на выход.
//
// Живой звук отдаёт Transport (транспорт поверх движка), потому что он же
// считает музыкальное время и обязан ставить удары на точные сэмплы.
#pragma once

#include <stdint.h>

class AudioSource {
 public:
  virtual ~AudioSource() = default;
  // Заполнить out ровно n сэмплами. Вызывается из задачи звука.
  virtual void render(int16_t* out, uint16_t n) = 0;
};
